export type Badge = { flag: string } | { colors: [string, string] } | { initial: string };

export function badgeOf(name: string): Badge {
  const flag = FLAG[name];
  if (flag) return { flag };
  const colors = COLORS[name];
  if (colors) return { colors };
  return { initial: name.replace(/^(fc|fk|ac|sc)\s+/i, "").charAt(0).toUpperCase() };
}
